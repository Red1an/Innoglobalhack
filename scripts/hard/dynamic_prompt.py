HOMOGLYPHS = str.maketrans("aceopxyKkMHTBAECOPX", "асеорхуКкМНТВАЕСОРХ")


def normalize(text):
    return "".join(part.translate(HOMOGLYPHS) if re.search(r"[а-яё]", part, re.I) else part
                   for part in re.split(r"(\s+)", text))


def build_prompt(text, base):
    lower = text.lower()
    blocks = [block for pattern, block in BLOCKS.values() if re.search(pattern, lower)]
    head = BASE if base == "own" else BENCH_PROMPT.split("Ответь только JSON")[0]
    return head + "\n" + GENERAL + "".join("\n" + block for block in blocks) + TAIL, len(blocks)


def ask(tag, prompt, text):
    schema = {"type": "object", "required": ["labels"], "additionalProperties": False,
              "properties": {"labels": {"type": "array", "items": {"type": "integer", "enum": MC}}}}
    payload = {"model": tag, "stream": False, "format": schema, "keep_alive": "10m",
               "messages": [{"role": "system", "content": prompt},
                            {"role": "user", "content": json.dumps({"mcId": 101, "description": text}, ensure_ascii=False)}],
               "options": {"temperature": 0, "seed": 42, "num_ctx": 6144, "num_predict": 64}}
    request = Request("http://localhost:11434/api/chat", data=json.dumps(payload).encode(),
                      headers={"Content-Type": "application/json"})
    return sorted(set(json.loads(json.load(urlopen(request, timeout=900))["message"]["content"])["labels"]))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="avibe-q8", choices=sorted(TAGS))
    parser.add_argument("--base", default="bench", choices=["bench", "own"])
    args = parser.parse_args()
    sheet = load_workbook(ROOT / "data/hard/hard_v0.xlsx")["разметка"]
    predictions = []
    for row in sheet.iter_rows(min_row=2):
        start = time.time()
        text = normalize(row[1].value)
        prompt, blocks = build_prompt(text, args.base)
        predictions.append(ask(TAGS[args.model], prompt, text))
        print(row[0].value, predictions[-1], "блоков", blocks, round(time.time() - start, 1), flush=True)
    urlopen(Request("http://localhost:11434/api/generate",
                    data=json.dumps({"model": TAGS[args.model], "keep_alive": 0}).encode()))
    stored = json.loads(OUT.read_text()) if OUT.exists() else {}
    stored[f"{args.model} dynamic {args.base}"] = predictions
    OUT.write_text(json.dumps(stored, ensure_ascii=False))


if __name__ == "__main__":
    main()
