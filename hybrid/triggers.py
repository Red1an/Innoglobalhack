SENTENCE_SPLIT = re.compile(r"(?<=[.!?;])\s+|\n+")


def classes_in(fragment):
    return {c for c, rx in CLASS_RE.items() if c != 101 and rx.search(fragment)}


def detect(text):
    """Return {trigger_name: set_of_affected_categories} for triggers that fire on text."""
    low = text.casefold()
    sentences = [s for s in SENTENCE_SPLIT.split(low) if s.strip()]
    fired = {}
    for t in TRIGGERS:
        rx = re.compile(t.pattern, re.I)
        if t.scope == "window":
            hit = set()
            for m in rx.finditer(low):
                hit |= classes_in(m.group(0))
            if hit:
                fired[t.name] = hit
        elif t.scope == "sentence":
            hit = set()
            for s in sentences:
                if rx.search(s):
                    hit |= classes_in(s) | set(t.classes)
            if hit:
                fired[t.name] = hit
        elif t.scope.startswith("text_unless:"):
            if rx.search(low) and not re.search(t.scope.split(":", 1)[1], low):
                fired[t.name] = set(t.classes)
        elif t.scope.startswith("text_if:"):
            if rx.search(low) and re.search(t.scope.split(":", 1)[1], low):
                fired[t.name] = set(t.classes)
        elif rx.search(low):
            if t.name == "seo_tail":
                m = rx.search(low)
                hit = classes_in(low[m.start():]) - classes_in(low[:m.start()])
                if hit:
                    fired[t.name] = hit
            else:
                fired[t.name] = set(t.classes)
    return fired


def complex_repair(text):
    return bool(CLASS_RE[101].search(text.casefold()))


