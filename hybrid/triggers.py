NEG_SKIP = r"(?!нужно|надо|пришл|ищ|потер|прост|тольк|видн|хват|взять|долг|необосн|посредник|предоплат|накрут|луж|материал)"
NEG = (r"(?:\bне\b|\bбез\b|\bкроме\b|\bникак\w*)[^\S\n]+" + NEG_SKIP + r"(?:[\w-]+[^\S\n]+){0,3}?[\w-]*(?:" + "|".join(CLASS_WORDS[c] for c in range(102, 107)) + r")[\w-]*"
       r"|(?:" + "|".join(CLASS_WORDS[c] for c in range(102, 107)) + r")[\w-]*(?:[^\S\n]+[\w-]+){0,3}?[^\S\n]+(?:не|нет)[^\S\n]+(?:дела|выполня|занима|бер|оказыва|предлага|включ|монтир|клад|красим|клеим)\w*")


@dataclass(frozen=True)
class Trigger:
    name: str
    pattern: str
    scope: str
    classes: tuple
    rule: str
    blocks: bool = True


